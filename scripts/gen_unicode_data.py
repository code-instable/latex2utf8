#!/usr/bin/env python3
"""Regenerate the Unicode-derived data files in symbols/data/.

    python3 scripts/gen_unicode_data.py

Writes:
  compose.tsv    base + combining mark -> precomposed character (canonical composition)
  fractions.tsv  n/d -> vulgar fraction character

Both are derived purely from Python's unicodedata, so the output depends on the
Unicode version of the interpreter (recorded in the file headers). The files are
committed; this script only needs to run when Unicode changes.
"""
import pathlib
import unicodedata

DATA = pathlib.Path(__file__).resolve().parent.parent / "symbols" / "data"
UNICODE = unicodedata.unidata_version


def compose_pairs():
    """Every (base, mark) pair that NFC composes into a single character."""
    pairs = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        decomp = unicodedata.decomposition(ch)
        if not decomp or decomp.startswith("<"):
            continue  # no decomposition, or a compatibility one
        parts = [int(p, 16) for p in decomp.split()]
        if len(parts) != 2:
            continue
        base, mark = parts
        if unicodedata.combining(chr(mark)) == 0:
            continue  # only real combining marks
        # composition exclusions (e.g. U+0958) do not recompose under NFC
        if unicodedata.normalize("NFC", chr(base) + chr(mark)) != ch:
            continue
        pairs[(base, mark)] = cp
    return pairs


def fractions():
    """n/d for every character with a <fraction> compatibility decomposition."""
    out = {}
    for cp in range(0x110000):
        ch = chr(cp)
        decomp = unicodedata.decomposition(ch)
        if not decomp.startswith("<fraction>"):
            continue
        text = "".join(chr(int(p, 16)) for p in decomp.split()[1:])
        if "⁄" not in text:
            continue
        num, _, den = text.partition("⁄")
        if num and den:  # skip U+215F, which has a numerator only
            out[f"{num}/{den}"] = ch
    return out


def main():
    pairs = compose_pairs()
    lines = [
        "# lutf composition table: <base hex>TAB<mark hex>TAB<result hex>",
        "# Generated by scripts/gen_unicode_data.py from Unicode %s. Do not edit." % UNICODE,
        "",
    ]
    for (base, mark), cp in sorted(pairs.items()):
        lines.append("%04X\t%04X\t%04X" % (base, mark, cp))
    (DATA / "compose.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("compose.tsv: %d pairs" % len(pairs))

    fr = fractions()
    lines = [
        "# lutf vulgar fractions: <numerator>/<denominator>TAB<character>",
        "# Generated by scripts/gen_unicode_data.py from Unicode %s. Do not edit." % UNICODE,
        "",
    ]
    for key in sorted(fr, key=lambda s: (int(s.split("/")[0]), int(s.split("/")[1]))):
        lines.append("%s\t%s" % (key, fr[key]))
    (DATA / "fractions.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("fractions.tsv: %d fractions" % len(fr))


if __name__ == "__main__":
    main()
